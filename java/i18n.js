/**
 * Handle Language Switching
 */
function setLanguage(lang) {
    if (!i18nData[lang]) return;
    
    localStorage.setItem('zorenb_lang', lang);
    document.documentElement.lang = lang;
    
    // 1. Update all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        let key = el.getAttribute('data-i18n');
        
        // Handle attribute translation like [title]tooltip_key
        const attrMatch = key.match(/^\[([a-z-]+)\](.*)/);
        if (attrMatch) {
            const attr = attrMatch[1];
            const realKey = attrMatch[2];
            if (i18nData[lang][realKey]) {
                el.setAttribute(attr, i18nData[lang][realKey]);
            }
            return;
        }

        if (i18nData[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = i18nData[lang][key];
            } else {
                if (i18nData[lang][key].includes('<br>')) {
                    el.innerHTML = i18nData[lang][key];
                } else {
                    el.textContent = i18nData[lang][key];
                }
            }
        }
    });

    // 2. Update specific UI components if needed (custom events)
    const event = new CustomEvent('languageChanged', { detail: lang });
    window.dispatchEvent(event);

    // 3. Update active flag in UI
    updateLanguageUI(lang);
}

function updateLanguageUI(lang) {
    const selectorBtn = document.querySelector('.lang-current-flag');
    if (selectorBtn) {
        const flags = {
            vi: '🇻🇳', en: '🇺🇸', fr: '🇫🇷', ko: '🇰🇷', ja: '🇯🇵', zh: '🇨🇳'
        };
        selectorBtn.textContent = flags[lang];
    }
    
    // Highlight active in dropdown
    document.querySelectorAll('.lang-option').forEach(opt => {
        // More robust check foronclick string
        const onClickStr = opt.getAttribute('onclick') || '';
        if (onClickStr.includes(`'${lang}'`) || onClickStr.includes(`"${lang}"`)) {
            opt.classList.add('active');
        } else {
            opt.classList.remove('active');
        }
    });
}

